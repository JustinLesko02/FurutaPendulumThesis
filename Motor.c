void motor_commutate(motor* motor, int encoder_ticks){

	if (motor->effort>100){
		motor->effort = 100;
	}

	else if (motor->effort<-100){
		motor->effort = -100;
	}
	if (motor->effort<0){
		effort = -motor->effort;
		offset = -motor->encoder_offset;
	}
	else{
		effort = motor->effort;
		offset = motor->encoder_offset;
	}

	int32_t input_angle = (int32_t) encoder_ticks -(int32_t) motor->encoder_zero + (int32_t) offset;
	input_angle = (input_angle)%motor_pulseperrev;

	if (input_angle<0){
		input_angle+= motor_pulseperrev;
	}
	inputangle = input_angle;
	_encoder_offset = motor->encoder_offset;

	ETheta = (pole_pairs*lookup_table_length*(input_angle)/motor_pulseperrev)%(lookup_table_length);
	Va = ((int32_t) motor->max_PWM+1)/2+cosLookupTable[ETheta];
	Vb = ((int32_t) motor->max_PWM+1)/2+(-cosLookupTable[ETheta]/2+(866)*sineLookupTable[ETheta]/1000);
	Vc = ((int32_t) motor->max_PWM+1)/2+(-cosLookupTable[ETheta]/2-(866)*sineLookupTable[ETheta]/1000);
	motor->TIM->CCR1 = (uint16_t) (effort* Va/100);
	motor->TIM->CCR2 = (uint16_t) (effort* Vb/100);
	motor->TIM->CCR3 = (uint16_t) (effort* Vc/100);
	motor->Va = Va;
	motor->Vb = Vb;
	motor->Vc = Vc;
}

void motor_enable(motor* motor){
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In1, GPIO_PIN_SET);
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In2, GPIO_PIN_SET);
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In3, GPIO_PIN_SET);
}

void motor_disable(motor* motor){
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In1, GPIO_PIN_RESET);
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In2, GPIO_PIN_RESET);
	HAL_GPIO_WritePin(motor->GPIOIn, motor->In3, GPIO_PIN_RESET);
}

