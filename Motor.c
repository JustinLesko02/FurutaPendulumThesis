void motor_initialize(motor* motor){
	HAL_TIM_PWM_Start(motor->htim, motor->Channel1);
	HAL_TIM_PWM_Start(motor->htim, motor->Channel2);
	HAL_TIM_PWM_Start(motor->htim, motor->Channel3);
	motor->max_PWM = motor->TIM->ARR;
	MAX_PWM = motor->max_PWM;
	motor_disable(motor);
}

